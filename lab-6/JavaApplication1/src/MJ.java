    private void clearErrorOnEdit(final JTextField field) {
        field.getDocument().addDocumentListener(new DocumentListener() {
            @Override public void insertUpdate(DocumentEvent e) { flag(field, false); }
            @Override public void removeUpdate(DocumentEvent e) { flag(field, false); }
            @Override public void changedUpdate(DocumentEvent e) { flag(field, false); }
        });
    }

    // ---------------- Actions ----------------

    private void saveStudent() {
        if (!validateForm()) {
            return;
        }
        String id = txtId.getText().trim();
        if (indexOfId(id) >= 0) {
            flag(txtId, true);
            showMessage("A student with ID \"" + id + "\" already exists. Use Update to change it.", false);
            return;
        }
        students.add(currentRecord());
        String name = txtName.getText().trim();
        clearFields();
        showMessage("Student \"" + name + "\" saved. Total students: " + students.size() + ".", true);
    }

    private void updateStudent() {
        if (!validateForm()) {
            return;
        }
        String id = txtId.getText().trim();
        int index = indexOfId(id);
        if (index < 0) {
            flag(txtId, true);
            showMessage("No student with ID \"" + id + "\" was found. Use Save Student to add a new one.", false);
            return;
        }
        students.set(index, currentRecord());
        showMessage("Student \"" + txtName.getText().trim() + "\" updated.", true);
    }

    private void deleteStudent() {
        String id = txtId.getText().trim();
        if (id.isEmpty()) {
            flag(txtId, true);
            showMessage("Enter the ID of the student you want to delete.", false);
            return;
        }
        int index = indexOfId(id);
        if (index < 0) {
            flag(txtId, true);
            showMessage("No student with ID \"" + id + "\" was found.", false);
            return;
        }
        String name = students.get(index)[1];
        int choice = JOptionPane.showConfirmDialog(this,
                "Delete \"" + name + "\" (" + id + ")? This cannot be undone.",
                "Confirm delete", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
        if (choice != JOptionPane.YES_OPTION) {
            return;
        }
        students.remove(index);
        clearFields();
        showMessage("Student \"" + name + "\" deleted. Total students: " + students.size() + ".", true);
    }

    private void resetForm() {
        clearFields();
        showTip();
        txtName.requestFocusInWindow();
    }

    private void loadById() {
        String id = txtId.getText().trim();
        int index = indexOfId(id);
        if (id.isEmpty() || index < 0) {
            if (!id.isEmpty()) {
                showMessage("No student with ID \"" + id + "\" was found.", false);
            }
            return;
        }
        String[] r = students.get(index);
        txtName.setText(r[1]);
        txtEmail.setText(r[2]);
        txtPhone.setText(r[3]);
        cmbDepartment.setSelectedItem(r[4]);
        cmbGender.setSelectedItem(r[5]);
        txtAddress.setText(r[6]);
        txtId.setText(r[0]);
        showMessage("Loaded \"" + r[1] + "\". Edit the fields and press Update, or press Delete.", true);
    }

    private void clearFields() {
        txtName.setText("");
        txtId.setText("");
        txtEmail.setText("");
        txtPhone.setText("");
        txtAddress.setText("");
        cmbDepartment.setSelectedIndex(0);
        cmbGender.setSelectedIndex(0);
        flag(txtName, false);
        flag(txtId, false);
        flag(txtEmail, false);
        flag(txtPhone, false);
        flag(cmbDepartment, false);
        flag(cmbGender, false);
    }

    private String[] currentRecord() {
        return new String[] {
            txtId.getText().trim(),
            txtName.getText().trim(),
            txtEmail.getText().trim(),
            txtPhone.getText().trim(),
            String.valueOf(cmbDepartment.getSelectedItem()),
            String.valueOf(cmbGender.getSelectedItem()),
            txtAddress.getText().trim()
        };
    }

    private int indexOfId(String id) {
        for (int i = 0; i < students.size(); i++) {
            if (students.get(i)[0].equalsIgnoreCase(id)) {
                return i;
            }
        }
        return -1;
    }

    // ---------------- Validation ----------------

    /** Validates every field, flags the bad ones and reports the first problem. */
    private boolean validateForm() {
        String name = txtName.getText().trim();
        String id = txtId.getText().trim();
        String email = txtEmail.getText().trim();
        String phone = txtPhone.getText().replaceAll("[\\s-]", "");

        String nameMsg = name.isEmpty() ? "Student name is required."
                : !name.matches("\\p{L}[\\p{L} .'\\-]{1,59}") ? "Enter a valid name (letters only)." : null;
        String idMsg = id.isEmpty() ? "Student ID is required."
                : !id.matches("[A-Za-z0-9_/\\-]{3,20}") ? "Student ID must be 3-20 letters, digits, - _ or /." : null;
        String emailMsg = email.isEmpty() ? "Email address is required."
                : !email.matches("[\\w.+\\-]+@[\\w\\-]+(\\.[\\w\\-]+)+") ? "Enter a valid email address." : null;
        String phoneMsg = phone.isEmpty() ? "Phone number is required."
                : !phone.matches("\\+?\\d{7,15}") ? "Enter a valid phone number." : null;
        String deptMsg = cmbDepartment.getSelectedIndex() <= 0 ? "Please select a department." : null;
        String genderMsg = cmbGender.getSelectedIndex() <= 0 ? "Please select a gender." : null;

        flag(txtName, nameMsg != null);
        flag(txtId, idMsg != null);
        flag(txtEmail, emailMsg != null);
        flag(txtPhone, phoneMsg != null);
        flag(cmbDepartment, deptMsg != null);
        flag(cmbGender, genderMsg != null);

        String[] messages = { nameMsg, idMsg, emailMsg, phoneMsg, deptMsg, genderMsg };
        for (String m : messages) {
            if (m != null) {
                showMessage(m, false);
                return false;
            }
        }
        return true;
    }

    private void flag(JComponent c, boolean invalid) {
        c.putClientProperty("error", invalid);
        c.repaint();
    }

    private void showMessage(String message, boolean success) {
        lblMessage.setForeground(success ? GREEN : INVALID);
        lblMessage.setText(message);
        messageTimer.restart();
    }

    private void showTip() {
        lblMessage.setForeground(MUTED);
        lblMessage.setText(TIP);
    }

