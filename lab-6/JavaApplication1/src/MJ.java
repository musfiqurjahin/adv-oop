    /** Text area UI that shows hint text while the area is empty. */
    private static final class HintAreaUI extends BasicTextAreaUI {
        private final String hint;

        HintAreaUI(String hint) {
            this.hint = hint;
        }

        @Override
        protected void paintSafely(Graphics g) {
            super.paintSafely(g);
            JTextComponent c = getComponent();
            if (c.getText().isEmpty()) {
                Graphics2D g2 = antialiased(g);
                g2.setFont(c.getFont());
                g2.setColor(HINT);
                g2.drawString(hint, c.getInsets().left, c.getInsets().top + g2.getFontMetrics().getAscent());
                g2.dispose();
            }
        }
    }

    /** Flat rounded button with hover / pressed / disabled states. */
    private static final class RoundButtonUI extends MetalButtonUI {
        @Override
        public void paint(Graphics g, JComponent c) {
            AbstractButton b = (AbstractButton) c;
            ButtonModel m = b.getModel();
            Color base = b.getBackground();
            boolean light = base.getRed() > 200;
            Color fill = base;
            if (!b.isEnabled()) {
                fill = new Color(228, 232, 239);
            } else if (m.isPressed()) {
                fill = base.darker();
            } else if (m.isRollover()) {
                fill = light ? new Color(220, 226, 236)
                             : new Color(Math.min(255, base.getRed() + 18),
                                         Math.min(255, base.getGreen() + 18),
                                         Math.min(255, base.getBlue() + 18));
            }
            Graphics2D g2 = antialiased(g);
            g2.setColor(fill);
            g2.fill(new RoundRectangle2D.Float(0, 0, c.getWidth(), c.getHeight(), ARC + 2, ARC + 2));
            g2.dispose();
            super.paint(g, c);
        }
    }

    /** Combo box UI: rounded border, chevron arrow, no gradient. */
    private static final class FlatComboUI extends BasicComboBoxUI {
        @Override
        protected JButton createArrowButton() {
            JButton b = new JButton() {
                @Override
                public void paint(Graphics g) {
                    Graphics2D g2 = antialiased(g);
                    g2.setColor(MUTED);
                    g2.setStroke(new BasicStroke(1.8f, BasicStroke.CAP_ROUND, BasicStroke.JOIN_ROUND));
                    int cx = getWidth() / 2, cy = getHeight() / 2;
                    g2.drawLine(cx - 5, cy - 2, cx, cy + 3);
                    g2.drawLine(cx, cy + 3, cx + 5, cy - 2);
                    g2.dispose();
                }
            };
            b.setBorder(new EmptyBorder(0, 0, 0, 0));
            b.setContentAreaFilled(false);
            b.setFocusable(false);
            return b;
        }

        @Override
        protected ComboPopup createPopup() {
            BasicComboPopup popup = (BasicComboPopup) super.createPopup();
            popup.setBorder(new LineBorder(LINE));
            return popup;
        }

        @Override
        public void paint(Graphics g, JComponent c) {
            Graphics2D g2 = antialiased(g);
            RoundRectangle2D shape = new RoundRectangle2D.Float(0.5f, 0.5f, c.getWidth() - 1, c.getHeight() - 1, ARC, ARC);
            g2.setColor(Color.WHITE);
            g2.fill(shape);
            boolean invalid = Boolean.TRUE.equals(c.getClientProperty("error"));
            boolean active = comboBox.hasFocus() || comboBox.isPopupVisible();
            g2.setColor(invalid ? INVALID : (active ? BLUE : LINE));
            g2.setStroke(new BasicStroke(active || invalid ? 1.6f : 1f));
            g2.draw(shape);
            g2.dispose();
            super.paint(g, c);
        }

        @Override
        public void paintCurrentValueBackground(Graphics g, Rectangle bounds, boolean hasFocus) {
            // transparent: the rounded background is painted in paint()
        }
    }

    /** Renders combo items; "Select ..." placeholders are greyed out. */
    private static final class ComboRenderer extends javax.swing.DefaultListCellRenderer {
        @Override
        public Component getListCellRendererComponent(JList<?> list, Object value, int index,
                                                      boolean selected, boolean focus) {
            JLabel label = (JLabel) super.getListCellRendererComponent(list, value, index, false, false);
            boolean placeholder = value != null && value.toString().startsWith("Select ");
            label.setFont(font(Font.PLAIN, 14));
            label.setForeground(placeholder ? HINT : TEXT);
            if (index < 0) {                       // value shown in the closed combo box
                label.setOpaque(false);
                label.setBorder(new EmptyBorder(0, 12, 0, 8));
            } else {                               // drop-down items
                label.setOpaque(true);
                label.setBackground(selected ? SELECTION : Color.WHITE);
                label.setBorder(new EmptyBorder(8, 12, 8, 8));
            }
            return label;
        }
    }

    /** Slim, flat scroll bar. */
    private static final class ThinScrollBarUI extends BasicScrollBarUI {
        @Override protected JButton createDecreaseButton(int orientation) { return emptyButton(); }
        @Override protected JButton createIncreaseButton(int orientation) { return emptyButton(); }

        private JButton emptyButton() {
            JButton b = new JButton();
            b.setPreferredSize(new Dimension(0, 0));
            b.setMinimumSize(new Dimension(0, 0));
            b.setMaximumSize(new Dimension(0, 0));
            return b;
        }

        @Override
        protected void paintTrack(Graphics g, JComponent c, Rectangle trackBounds) {
            // no track
        }

        @Override
        protected void paintThumb(Graphics g, JComponent c, Rectangle r) {
            if (r.isEmpty() || !scrollbar.isEnabled()) {
                return;
            }
            Graphics2D g2 = antialiased(g);
            g2.setColor(isDragging ? new Color(160, 172, 190) : new Color(200, 208, 220));
            g2.fillRoundRect(r.x + 2, r.y + 2, r.width - 4, r.height - 4, 7, 7);
            g2.dispose();
        }
    }

